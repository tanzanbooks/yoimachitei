def draw_cards():
    """重複しない3枚を選び、正位置・逆位置を半々で決める。"""
    results = []
    for card in random.sample(CARDS, 3):
        reversed_card = random.choice([False, True])
        name, upright, reversed_meaning = card
        direction = "逆位置" if reversed_card else "正位置"
        meaning = reversed_meaning if reversed_card else upright
        results.append((name, direction, meaning))
    return results


